import { installStep, installDevStep } from './utils.js';

const DATE = new Date().toISOString().split('T')[0];

export default {
  name: 'Railway Postgres',
  description: 'Set up Railway-hosted Postgres with Drizzle ORM — one-click DB deployment',
  category: 'Database — SQL (Managed Cloud)',
  supportedFrameworks: [],

  steps(context) {
    const { hasTypescript, packageManager } = context;
    const ext = hasTypescript ? 'ts' : 'js';

    const dbFile = hasTypescript
      ? `import { drizzle } from 'drizzle-orm/node-postgres';
import { Pool } from 'pg';
import * as schema from './schema';

const pool = new Pool({
  connectionString: process.env.DATABASE_URL!,
  ssl: {
    rejectUnauthorized: false,
  },
});

export const db = drizzle(pool, { schema });
`
      : `import { drizzle } from 'drizzle-orm/node-postgres';
import { Pool } from 'pg';
import * as schema from './schema.js';

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: {
    rejectUnauthorized: false,
  },
});

export const db = drizzle(pool, { schema });
`;

    const schemaFile = hasTypescript
      ? `import { pgTable, serial, text, timestamp } from 'drizzle-orm/pg-core';

export const users = pgTable('users', {
  id: serial('id').primaryKey(),
  name: text('name').notNull(),
  email: text('email').notNull().unique(),
  createdAt: timestamp('created_at').defaultNow().notNull(),
});
`
      : `import { pgTable, serial, text, timestamp } from 'drizzle-orm/pg-core';

export const users = pgTable('users', {
  id: serial('id').primaryKey(),
  name: text('name').notNull(),
  email: text('email').notNull().unique(),
  createdAt: timestamp('created_at').defaultNow().notNull(),
});
`;

    const drizzleConfig = hasTypescript
      ? `import type { Config } from 'drizzle-kit';

export default {
  schema: './lib/schema.ts',
  out: './drizzle',
  dialect: 'postgresql',
  dbCredentials: {
    url: process.env.DATABASE_URL!,
  },
} satisfies Config;
`
      : `/** @type { import("drizzle-kit").Config } */
export default {
  schema: './lib/schema.js',
  out: './drizzle',
  dialect: 'postgresql',
  dbCredentials: {
    url: process.env.DATABASE_URL,
  },
};
`;

    return [
      installStep(packageManager, ['pg', 'drizzle-orm']),
      installDevStep(packageManager, ['drizzle-kit', '@types/pg'], 'Install drizzle-kit, @types/pg (dev)'),
      {
        type: 'write',
        label: `Write lib/db.${ext}`,
        filePath: `lib/db.${ext}`,
        content: dbFile,
      },
      {
        type: 'write',
        label: `Write lib/schema.${ext}`,
        filePath: `lib/schema.${ext}`,
        content: schemaFile,
      },
      {
        type: 'write',
        label: `Write drizzle.config.${ext}`,
        filePath: `drizzle.config.${ext}`,
        content: drizzleConfig,
      },
      {
        type: 'env',
        label: 'Add DATABASE_URL to .env.example',
        vars: {
          DATABASE_URL: 'postgresql://postgres:password@host.railway.app:5432/railway',
        },
      },
      {
        type: 'doc',
        label: 'Write docs/railway-postgres.md',
        content: docContent(DATE),
      },
    ];
  },

  nextSteps() {
    return [
      'Create a Railway project at https://railway.app',
      'Add a Postgres service (New → Database → Add PostgreSQL)',
      'Copy the DATABASE_URL from your Postgres service → Variables tab',
      'Paste it into your .env file',
      'Push your schema: `npx drizzle-kit push`',
      'Deploy your app on Railway too for zero-config DATABASE_URL injection',
    ];
  },
};

function docContent(date) {
  return `# Railway Postgres Setup Guide
> Generated by ai-scaffold on ${date}

## What is Railway?
Railway is a developer-friendly cloud platform where you can deploy Postgres (and your app) in seconds. When your app and database are both on Railway, the DATABASE_URL is injected automatically.

## What was set up
| Item | Detail |
|------|--------|
| Packages | \`pg\`, \`drizzle-orm\` |
| Dev packages | \`drizzle-kit\`, \`@types/pg\` |
| \`lib/db.js\` | Drizzle + node-postgres with SSL |
| \`lib/schema.js\` | Example users table |
| \`drizzle.config.js\` | Drizzle Kit configuration |

## Environment Variables
| Variable | Description | Where to get it |
|----------|-------------|-----------------|
| \`DATABASE_URL\` | Postgres connection string | Railway → Postgres service → Variables |

## Getting Started with Railway
1. Go to https://railway.app and sign in
2. New Project → Database → Add PostgreSQL
3. Click the Postgres service → Variables tab
4. Copy \`DATABASE_URL\` into your local \`.env\`

## Usage

### Querying with Drizzle
\`\`\`js
import { db } from '@/lib/db';
import { users } from '@/lib/schema';
import { eq } from 'drizzle-orm';

const allUsers = await db.select().from(users);
await db.insert(users).values({ name: 'Alice', email: 'alice@example.com' });
await db.update(users).set({ name: 'Bob' }).where(eq(users.id, 1));
await db.delete(users).where(eq(users.id, 1));
\`\`\`

### Schema Management
\`\`\`bash
npx drizzle-kit push
npx drizzle-kit studio
npx drizzle-kit generate
\`\`\`

## Auto-Injection on Railway
When your app runs on Railway and references the same project's Postgres service, \`DATABASE_URL\` is automatically injected — no manual copy-paste needed.

## Production Checklist
- [ ] Create Postgres service at https://railway.app
- [ ] Set DATABASE_URL in your hosting env (auto-injected if on Railway)
- [ ] Set up daily backups in Railway settings
- [ ] Enable connection pooling for high-traffic apps (consider using PgBouncer)

## Resources
- [Railway Docs](https://docs.railway.app)
- [Railway Postgres](https://docs.railway.app/databases/postgresql)
- [Drizzle ORM Docs](https://orm.drizzle.team)
`;
}
